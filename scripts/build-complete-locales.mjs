function deepClone(obj) {
  return JSON.parse(JSON.stringify(obj));
}

// Ensure key structure matches en exactly
function syncWithBase(base, target) {
  const result = {};
  for (const key of Object.keys(base)) {
    if (typeof base[key] === "object" && base[key] !== null) {
      result[key] = syncWithBase(base[key], target && target[key] ? target[key] : {});
    } else {
      result[key] = target && target[key] ? target[key] : base[key];
    }
  }
  return result;
}

